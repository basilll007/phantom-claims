"""Generate paper/numbers.tex: one LaTeX macro per number used in the paper, each sourced from a
results/results.jsonl record (latest per id) or a results/tables file. Missing -> \\TODOVERIFY{...}."""
import json, math, os

R = {}
for line in open("results/results.jsonl"):
    if line.strip():
        r = json.loads(line); R[r["id"]] = r
out = ["% AUTO-GENERATED by scripts/make_paper_numbers.py from results/results.jsonl -- do not edit by hand",
       "\\providecommand{\\TODOVERIFY}[1]{\\textbf{[TODO-VERIFY: #1]}}"]
used = {}


def first(*ids):
    for i in ids:
        if i in R:
            return R[i]
    return None


def num(name, rec, path, nd=2, pct=False):
    v = rec
    try:
        for p in path:
            v = v[p]
        if v is None or (isinstance(v, float) and math.isnan(v)):
            raise KeyError
        s = f"{100 * v:.0f}\\%" if pct else (f"{v:.{nd}f}" if isinstance(v, float) else str(v))
        used[name] = dict(id=rec["id"], path=list(map(str, path)), value=v)
    except Exception:
        s = f"\\TODOVERIFY{{{name}}}"
    out.append(f"\\newcommand{{\\{name}}}{{{s}}}")


def ci(name, rec, key):
    if rec is None:
        out.append(f"\\newcommand{{\\{name}}}{{\\TODOVERIFY{{{name}}}}}"); return
    try:
        lo, hi = rec["ci"][key]
        out.append(f"\\newcommand{{\\{name}}}{{[{lo:.2f}, {hi:.2f}]}}")
        used[name] = dict(id=rec["id"], path=["ci", key], value=[lo, hi])
    except Exception:
        out.append(f"\\newcommand{{\\{name}}}{{\\TODOVERIFY{{{name}}}}}")


L = "ABCDEFGHIJ"
def tag(s):  # macro-safe (digits spelled out so breast_rep1 / breast_rep2 do not collide)
    s = s.replace("0", "zero").replace("1", "one").replace("2", "two").replace("5", "five")
    return "".join(c for c in s.title() if c.isalpha())

# expression tools, H1/H2, K=10 and K=20
for split, tissue in [("dev", "breast_rep1"), ("test", "breast_rep1"), ("test", "breast_rep2"), ("test", "pancreas"), ("test", "lung")]:
    for m in ("cpdb", "prod"):
        for K in (10, 20):
            pre = f"{split}{tag(tissue)}{tag(m)}K{'Ten' if K == 10 else 'Twenty'}"
            r1 = first(f"{split}_{'default' if split == 'dev' else 'final'}_{tissue}_H1_expr_{m}_K{K}", f"dev_default_H1_expr_{m}_K{K}" if split == "dev" else "")
            r2 = first(f"{split}_{'default' if split == 'dev' else 'final'}_{tissue}_H2_expr_{m}_K{K}_none", f"dev_default_H2_expr_{m}_K{K}_none" if split == "dev" else "")
            num(pre + "PR", r1, ["metrics", "phantom_rate"]); ci(pre + "PRci", r1, "phantom_rate")
            num(pre + "PRafter", r2, ["metrics", "phantom_rate_after"]); ci(pre + "PRafterci", r2, "phantom_rate_after")
            num(pre + "Ret", r2, ["metrics", "retention"]); ci(pre + "Retci", r2, "retention")
            num(pre + "Red", r2, ["metrics", "rel_reduction"]); ci(pre + "Redci", r2, "rel_reduction")
# agents
for split in ("dev", "test"):
    for tissue in ("breast_rep1", "breast_rep2", "pancreas", "lung", "all"):
        for fam in ("gemini", "deepseek", "both"):
            pre = f"ag{tag(split)}{tag(tissue)}{tag(fam)}"
            r1 = first(f"agent_{split}_{tissue}_{fam}_unguided_K10")
            r2 = first(f"agent_{split}_{tissue}_{fam}_unguided_gated_K10")
            r3 = first(f"agent_{split}_{tissue}_{fam}_gate_tool_K10")
            if r1 is None:
                continue
            num(pre + "PR", r1, ["metrics", "phantom_rate"]); ci(pre + "PRci", r1, "phantom_rate")
            num(pre + "Runs", r1, ["n_runs"])
            num(pre + "PRafter", r2, ["metrics", "phantom_rate_after"])
            num(pre + "Ret", r2, ["metrics", "retention"]); ci(pre + "Retci", r2, "retention")
            num(pre + "ToolPR", r3, ["metrics", "phantom_rate"]); ci(pre + "ToolPRci", r3, "phantom_rate")
    c = first(f"agent_{split}_gate_tool_compliance")
    if c:
        for k in ("runs", "submitted", "verified_pass", "verified_fail_submitted", "unverified", "verified_fail_submitted_negatives"):
            num(f"comp{tag(split)}{tag(k)}", c, ["metrics", k])
# validity
c = first("dev_gate_null_calibration")
for v in ("full", "no_tiles"):
    num(f"calib{tag(v)}Five", c, ["metrics", v, "frac_p_lt_0_05"], pct=True)
    num(f"calib{tag(v)}N", c, ["metrics", v, "n"])
p = first("dev_gate_planted_pass_rates")
for v in ("full", "no_tiles", "no_split", "no_min_evidence", "no_perm"):
    for cat in ("true", "phantom", "niche", "random"):
        num(f"planted{tag(v)}{tag(cat)}", p, ["metrics", v, cat])
for t in ("breast_rep1", "breast_rep2", "pancreas", "lung"):
    r = first(f"test_final_planted_pass_rates_{t}")
    for cat in ("true", "phantom", "niche", "random"):
        num(f"testplanted{tag(t)}{tag(cat)}", r, ["metrics", cat])
r = first("real_breast_gate_check")
for k, nm in [("PD-L1/PD-1 case", "Pdl"), ("expr_top10_rep1", "Exprtop"), ("positive_control_contact", "Posctl")]:
    num(f"real{nm}Pass", r, ["metrics", k, "pass_both"]); num(f"real{nm}N", r, ["metrics", k, "n"])
# data
lr = json.load(open("results/tables/lr_pool.json"))
for t, v in lr.items():
    out.append(f"\\newcommand{{\\lr{tag(t)}}}{{{v['pairs_in_panel']}}}")
    out.append(f"\\newcommand{{\\panel{tag(t)}}}{{{v['panel_genes']}}}")
out.append(f"\\newcommand{{\\lrConsensus}}{{{lr['breast_rep1']['consensus_pairs']}}}")
import csv
for row in csv.DictReader(open("results/tables/cell_counts.csv")):
    if row["cell_type"] == "__TOTAL__":
        out.append(f"\\newcommand{{\\cells{tag(row['tissue'])}}}{{{int(row['n_cells']):,}}}".replace(",", "{,}"))
os.makedirs("paper", exist_ok=True)
open("paper/numbers.tex", "w").write("\n".join(out) + "\n")
json.dump(used, open("paper/numbers_provenance.json", "w"), indent=1, default=float)
print(len(used), "numbers with provenance;", sum("TODOVERIFY" in l for l in out), "missing")
