def num(name, rec, path, nd=2, pct=False):
    v = rec
    try:
        for p in path:
            v = v[p]
        if v is None or (isinstance(v, float) and math.isnan(v)):
            raise KeyError
        s = f"{100 * v:.0f}\\%" if pct else (f"{v:.{nd}f}" if isinstance(v, float) else str(v))
        used[name] = dict(id=rec["id"], path=list(map(str, path)), value=v)
    except Exception:
        s = f"\\TODOVERIFY{{{name}}}"
    out.append(f"\\newcommand{{\\{name}}}{{{s}}}")


def ci(name, rec, key):
    if rec is None:
        out.append(f"\\newcommand{{\\{name}}}{{\\TODOVERIFY{{{name}}}}}"); return
    try:
        lo, hi = rec["ci"][key]
        out.append(f"\\newcommand{{\\{name}}}{{[{lo:.2f}, {hi:.2f}]}}")
        used[name] = dict(id=rec["id"], path=["ci", key], value=[lo, hi])
    except Exception:
        out.append(f"\\newcommand{{\\{name}}}{{\\TODOVERIFY{{{name}}}}}")


